import asyncio

async def fetch_data():
    print('start fetching')
    await asyncio.sleep(2) # simulates waiting for network, doesn't block
    print('done fetching')
    return {'data': 123}

async def main():
    result = await fetch_data()
    print(result)

asyncio.run(main())